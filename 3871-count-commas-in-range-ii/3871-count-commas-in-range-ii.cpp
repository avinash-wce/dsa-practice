class Solution {
public:
    long long countCommas(long long n) {
        if (n < 1000){
            return 0;
        }
        if (n < 1000000){
            return n - 999;
        }
        if ( n < 1e9){
            return 999999-999 + ((n - 999999)*2);
        }
        if ( n < 1e12){
            return 999999-999 + ((999999999 - 999999)*2) + ((n - 999999999)*3);
        }
        if ( n < 1e15){
            return 999999-999 + ((999999999 - 999999)*2) + ((999999999999 - 999999999)*3) + ((n - 999999999999)*4);
        }
        else{
            return 999999-999 + ((999999999 - 999999)*2) + ((999999999999 - 999999999)*3) + ((n - 999999999999)*4) + 1;
        }
        return 0;
    }
};